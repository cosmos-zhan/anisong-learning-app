#!/usr/bin/env python3
"""Create launch-icon PNGs at all legacy launcher densities.

Usage: python3 tools/make_icon.py /path/to/authorized_cover.png
       python3 tools/make_icon.py --download
If download fails, uses the included simple flower illustration generated by Pillow, and warns.
"""
from pathlib import Path
import sys, urllib.request, io
from PIL import Image,ImageOps,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
url=(ROOT/'tools/cover-url.txt').read_text().strip()
cover=None
if len(sys.argv)>1 and sys.argv[1]=='--download':
    try:
        req=urllib.request.Request(url,headers={'User-Agent':'Mozilla/5.0 Haruhikage private prototype'})
        with urllib.request.urlopen(req, timeout=25) as resp:
            img=Image.open(io.BytesIO(resp.read())).convert('RGB')
            if min(img.size)<128: raise ValueError('cover image too small')
            cover=img
            print('Loaded CRYCHIC 春日影 single art:',img.size)
    except Exception as e:
        print('WARNING: album art download failed, keeping placeholder icon:',str(e),file=sys.stderr)
elif len(sys.argv)>1:
    cover=Image.open(sys.argv[1]).convert('RGB')
if cover is None:
    # Clearly marked original placeholder, not copied album artwork.
    N=512; cover=Image.new('RGB',(N,N),(221,236,220));d=ImageDraw.Draw(cover)
    for j in range(12):
        x=38+j*38;d.ellipse((x-35,30,x+90,500),outline=(187,209,182),width=3)
    for x,y in [(100,100),(220,180),(350,130),(425,290),(160,360),(315,405)]:
        for ox,oy in [(-18,0),(18,0),(0,-18),(0,18),(0,0)]:
            d.ellipse((x+ox-22,y+oy-22,x+ox+22,y+oy+22),fill=(249,252,246))
        d.ellipse((x-9,y-9,x+9,y+9),fill=(233,215,146))
    d.text((190,248),'春日影',fill=(90,117,111),font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',24))
for density,size in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
    dest=ROOT/'app/src/main/res'/f'mipmap-{density}';dest.mkdir(parents=True,exist_ok=True)
    icon=ImageOps.fit(cover,(size,size),method=Image.Resampling.LANCZOS)
    icon.save(dest/'ic_launcher.png')
    icon.save(dest/'ic_launcher_round.png')
print('Icon densities prepared')
